#!/usr/bin/env python3
"""Generate crates/ef-core/src/console_ids.rs: the console releases of the 2D games.

Facts only (titles, regions, serials, sizes and SHA-1 hashes) are taken from the redump and
No-Intro DAT files as distributed by libretro-database, at a pinned commit.  Usage:

    gen_legacy_ids.py <libretro-database checkout or directory holding the five .dat files> <output .rs>

Files read (paths relative to the libretro-database root, or bare names in the directory):

    metadat/redump/Sony - PlayStation.dat
    metadat/redump/Sega - Dreamcast.dat
    metadat/no-intro/Nintendo - Game Boy Color.dat
    metadat/no-intro/Nintendo - Game Boy Advance.dat

Disc releases are keyed by serial (PlayStation: the SYSTEM.CNF boot file name; Dreamcast: the
IP.BIN product number).  Serial spellings with variant suffixes in the DAT (for example
"SLUS-00106CE", "SLES-00032/COLL." or "SLES-000322" for redump's "SLES-00032#2") name the same
boot executable and are reduced to the plain serial.  ROMs are keyed by SHA-1.
"""
import os, re, sys

COMMIT = '12c21cf79f1e20eff6ac68b80875816c717d0a7a'

# Title prefixes of the 2D games in these DATs, and the Eyefinder game they are.
TITLES = [
    ('Grand Theft Auto - Mission Pack 1 - London 1969', 'London1969'),
    ('Grand Theft Auto - London 1969', 'London1969'),
    ('Grand Theft Auto 2', 'Gta2'),
    ('G.T.A - Grand Theft Auto', 'Gta1'),
    ('Pro Foot Contest \'98 + Grand Theft Auto + Courier Crisis', 'Gta1'),
    ('Grand Theft Auto', 'Gta1'),
]
SOURCES = [
    ('metadat/redump/Sony - PlayStation.dat', 'Ps1', 'disc'),
    ('metadat/redump/Sega - Dreamcast.dat', 'Dreamcast', 'disc'),
    ('metadat/no-intro/Nintendo - Game Boy Color.dat', 'GameBoyColor', 'rom'),
    ('metadat/no-intro/Nintendo - Game Boy Advance.dat', 'GameBoyAdvance', 'rom'),
]


def games(text):
    for m in re.finditer(r'^game \($(.*?)^\)$', text, re.M | re.S):
        body = m.group(1)
        name = re.search(r'^\s*name "([^"]*)"', body, re.M).group(1)
        region = re.search(r'^\s*region "([^"]*)"', body, re.M)
        serial = re.search(r'^\s*serial "([^"]*)"', body, re.M)
        roms = re.findall(r'rom \( name "([^"]*)" size (\d+) crc \w+ md5 \w+ sha1 (\w+)', body)
        yield name, region.group(1) if region else '', serial.group(1) if serial else '', roms


def game_of(name, platform):
    for prefix, game in TITLES:
        if name.startswith(prefix + ' (') or name == prefix:
            # GTA Advance is the Game Boy Advance "Grand Theft Auto".
            if game == 'Gta1' and platform == 'GameBoyAdvance':
                return 'GtaAdvance'
            return game
    return None


def plain_serial(s, platform):
    if platform == 'Ps1':
        m = re.match(r'^([A-Z]{4}-\d{5})', s)
        return m.group(1) if m else None
    return s or None


def main():
    root, out = sys.argv[1], sys.argv[2]
    discs, roms = {}, []
    for rel, platform, kind in SOURCES:
        path = os.path.join(root, rel)
        if not os.path.exists(path):
            path = os.path.join(root, os.path.basename(rel))
        text = open(path, encoding='utf-8').read()
        for name, region, serial, files in games(text):
            game = game_of(name, platform)
            if not game:
                continue
            if kind == 'disc':
                s = plain_serial(serial, platform)
                if s:
                    discs.setdefault((platform, s), (game, name))
            else:
                for fname, size, sha1 in files:
                    roms.append((platform, game, name, int(size), sha1.lower()))
    lines = [
        '// Generated by tools/gen_legacy_ids.py from libretro-database commit',
        f'// {COMMIT} (redump and No-Intro DAT files). Do not edit by hand.',
        '',
        'use crate::{Game, Platform};',
        '',
        '/// `(platform, serial or product number, game, DAT title)`.',
        'pub const DISCS: &[(Platform, &str, Game, &str)] = &[',
    ]
    for (platform, s), (game, name) in sorted(discs.items()):
        lines.append(f'    (Platform::{platform}, "{s}", Game::{game}, "{name}"),')
    lines += ['];', '', '/// `(platform, game, DAT title, size, SHA-1)`.', 'pub const ROMS: &[(Platform, Game, &str, u64, &str)] = &[']
    for platform, game, name, size, sha1 in sorted(roms):
        lines.append(f'    (Platform::{platform}, Game::{game}, "{name}", {size}, "{sha1}"),')
    lines += ['];', '']
    open(out, 'w').write('\n'.join(lines))


if __name__ == '__main__':
    main()
